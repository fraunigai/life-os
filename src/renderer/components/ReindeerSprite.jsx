// ── Rendering ───────────────────────────────────────────────────────────────
// One <rect> per horizontal run of the same colour key (computed once; ~1/3 of per-pixel rects).
function toRuns(rows) {
  const runs = []
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length;) {
      const ch = row[x]
      let end = x + 1
      while (end < row.length && row[end] === ch) end++
      if (PALETTE[ch]) runs.push({ ch, x, y, w: end - x })
      x = end
    }
  })
  return runs
}

const FACE_RUNS = toRuns(FACE)
const FRAMES = [...WALK, HOVER].map(toRuns)          // 0-3 = trot, 4 = hover
const FRAME_NOSE = [...NOSE.walk, NOSE.hover]
const HOVER_FRAME = 4

// Drawn in pixel units and scaled by px through the viewBox, so the runs never depend on px.
const PixelArt = memo(function PixelArt({ runs, cols, rows, px, hidden = false }) {
  return (
    <svg
      width={cols * px}
      height={rows * px}
      viewBox={`0 0 ${cols} ${rows}`}
      shapeRendering="crispEdges"
      aria-hidden="true"
      style={{ position: 'relative', display: hidden ? 'none' : 'block' }}
    >
      {runs.map(r => (
        <rect
          key={`${r.y}-${r.x}`}
          x={r.x} y={r.y} width={r.w} height={1}
          fill={PALETTE[r.ch]}
          className={r.ch === 'S' ? 'rd-scarf' : undefined}
        />
      ))}
    </svg>
  )
})

// Soft radial glow in the nose colour: stops .8 / .3 @45% / 0, radius 3.4 x px (min 8px).
const glowCache = new Map()
function glowBackground(strength) {
  if (!glowCache.has(strength)) {
    const a = k => withAlpha(PALETTE.N, k * strength)
    glowCache.set(strength, `radial-gradient(circle closest-side, ${a(0.8)} 0%, ${a(0.3)} 45%, ${a(0)} 100%)`)
  }
  return glowCache.get(strength)
}

// Positioned BEFORE the (position:relative) sprite svg, so it paints behind the pixels and only shows around the nose.
function NoseGlow({ at, px, strength = 1 }) {
  const r = Math.max(8, 3.4 * px)
  return (
    <span
      aria-hidden="true"
      className="rd-nose-glow"
      style={{
        position: 'absolute',
        left: at[0] * px - r,
        top: at[1] * px - r,
        width: 2 * r,
        height: 2 * r,
        borderRadius: '50%',
        background: glowBackground(strength),
        pointerEvents: 'none',
      }}
    />
  )
}

// `glow` scales the nose-glow strength (the design uses 0.8 for the small chat-header icon).
export function ReindeerFaceIcon({ px = 4, glow = 1 }) {
  return (
    <span
      aria-hidden="true"
      style={{ position: 'relative', display: 'block', flexShrink: 0, width: 10 * px, height: 10 * px }}
    >
      <NoseGlow at={NOSE.face} px={px} strength={glow} />
      <PixelArt runs={FACE_RUNS} cols={10} rows={10} px={px} />
    </span>
  )
}

// ── Walker ──────────────────────────────────────────────────────────────────
const PX = 3
const SPRITE_W = 20 * PX    // 60
const SPRITE_H = 18 * PX    // 54
const SIDEBAR = 200         // walk starts at the content edge
const FAB_CLEAR = 80        // turn around before the AI button (right-6 + w-14)
const TICK_MS = 80          // one step per tick; one trot frame per 2 ticks = 160ms
const SPEED = 1.5           // px per tick

export function WalkingReindeer({ onOpenAI }) {
  const [pos, setPos] = useState(60)
  const [dir, setDir] = useState(1)
  const [frame, setFrame] = useState(0)
  const [isHovered, setIsHovered] = useState(false)

  const stateRef = useRef({ pos: 60, dir: 1, step: 0, last: 0 })
  const hoveredRef = useRef(false)

  useEffect(() => {
    function maxX() {
      return Math.max(40, window.innerWidth - SIDEBAR - SPRITE_W - FAB_CLEAR)
    }

    let raf
    function tick(ts) {
      const s = stateRef.current
      // Only move while not hovered
      if (!hoveredRef.current && ts - s.last >= TICK_MS) {
        s.pos += s.dir * SPEED
        if (s.pos < 10 || s.pos > maxX()) {
          s.dir = -s.dir
          s.pos = Math.max(10, Math.min(maxX(), s.pos))
        }
        s.step++
        setPos(Math.round(s.pos))
        setDir(s.dir)
        setFrame(Math.floor(s.step / 2) % 4)
        s.last = ts
      }
      raf = requestAnimationFrame(tick)
    }
    raf = requestAnimationFrame(tick)
    return () => cancelAnimationFrame(raf)
  }, [])

  function handleMouseEnter() {
    hoveredRef.current = true
    setIsHovered(true)
  }
  function handleMouseLeave() {
    hoveredRef.current = false
    setIsHovered(false)
  }

  const shown = isHovered ? HOVER_FRAME : frame

  return (
    <div
      onClick={onOpenAI}
      onMouseEnter={handleMouseEnter}
      onMouseLeave={handleMouseLeave}
      aria-hidden="true"
      style={{
        position: 'fixed',
        bottom: 4,
        left: SIDEBAR + pos,
        width: SPRITE_W,
        height: SPRITE_H,
        zIndex: 20,
        cursor: 'pointer',
        animation: isHovered ? 'confusedShake 0.35s ease-in-out infinite' : undefined,
      }}
    >
      {/* Everything that faces a direction mirrors together: shadow, nose glow, sprite */}
      <div style={{ position: 'absolute', inset: 0, transform: dir < 0 ? 'scaleX(-1)' : undefined }}>
        {/* Ground shadow, under the legs (not the head) */}
        <div style={{
          position: 'absolute',
          bottom: -2,
          left: 8 * PX - 19,
          width: 38,
          height: 5,
          background: 'rgba(0,0,0,0.16)',
          borderRadius: '50%',
          filter: 'blur(2px)',
          pointerEvents: 'none',
        }} />
        <NoseGlow at={FRAME_NOSE[shown]} px={PX} />
        {FRAMES.map((runs, i) => (
          <PixelArt key={i} runs={runs} cols={20} rows={18} px={PX} hidden={i !== shown} />
        ))}
      </div>

      {/* Floating "?" when confused */}
      {isHovered && (
        <div style={{
          position: 'absolute',
          top: -20,
          left: '50%',
          transform: 'translateX(-50%)',
          background: c('amber'),
          color: c('on-amber'),
          fontWeight: 900,
          fontSize: 11,
          lineHeight: 1,
          padding: '2px 5px',
          borderRadius: 3,
          boxShadow: `0 2px 0 ${c('amber-shadow')}`,
          animation: 'questionBob 0.7s ease-in-out infinite',
          pointerEvents: 'none',
          fontFamily: 'monospace',
          whiteSpace: 'nowrap',
        }}>?</div>
      )}
    </div>
  )
}
